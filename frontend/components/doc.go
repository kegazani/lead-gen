// Package components — общий слой серверных UI-компонентов фронтенда: каркас
// страницы (layout), переиспользуемые фрагменты (notice, поле формы, вкладки,
// бейдж статуса, происхождение поля, живые объявления, бейдж верификации адреса)
// и разбор ошибок формы в представление. Компоненты собираются на html/template и
// не содержат ни доменных терминов, ни какого-либо доступа к бэкенду: их
// переиспользуют публичный edge (frontend/public) и консоль оператора.
//
// Слой обеспечивает единый источник пользовательского текста (каталог сообщений
// Messages и локализованные форматы Formatter), доступность (область aria-live,
// скип-ссылка, управление фокусом при подмене фрагментов скриптом
// console-a11y.js), безопасность ответов (NoStore) и ограничение частоты
// чувствительных действий (RateLimit).
//
// Компонентность здесь серверная: канон стека фиксирует серверный рендеринг
// html/template и гипермедиа-фрагменты HTMX, а SPA и отдельный фронтенд-процесс
// отклонены (docs/architecture.md §11; web-frontend-architecture, Решение 2).
// Пакет отвечает только за разметку и разбор ошибок в представление; маршруты,
// доступ, заголовки ответов и данные остаются за потребителем. Общая навигация
// консоли строится построителем ConsoleNav: канонический список разделов
// (ConsoleSections) и базовые адреса сервисов задаёт потребитель, а компонент
// только размечает пункты.
