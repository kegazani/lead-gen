package ports

import "time"

// Clock — источник текущего времени.
//
// Use cases читают время только через порт, чтобы тест управлял временем
// решений и сроком утверждения (ExpireApproval), не меняя доменный код и не
// завися от системных часов.
type Clock interface {
	// Now возвращает текущий момент времени.
	Now() time.Time
}
