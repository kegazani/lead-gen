// Package contracts фиксирует форму межконтекстных контрактов контекста
// outreach-orchestration.
//
// Публикуемый контракт `approved-action` (владелец — этот контекст) здесь заново
// не объявляется: единственный источник истины — опубликованный модуль
// lead-gen/contracts/outreach-orchestration/approvedaction, а пакет лишь
// реэкспортирует его типы и константы. Общий конверт Envelope тоже берётся из
// этого модуля (type alias).
//
// Потребляемые контракты объявлены антикоррупционными DTO потребителя:
// `campaign-command` (команда кампании), `audience-snapshot` (ссылка на снимок
// аудитории, владелец audience), `engagement-event` (реакция получателя, владелец
// engagement-observation) и `processing-authority` (снимок политики, владелец
// data-governance). Типы владельца в этот пакет не импортируются: DTO объявляет
// ровно те поля, которые нужны потребителю.
//
// Через границу контекста проходят только минимальные идентификаторы и ссылки.
// Внутренние таблицы и интернины агрегата, типы SDK поставщиков, а также
// персональные данные (адреса, имена, тела писем) в контракты не попадают
// (docs/domain-model.md, «Privacy by boundary»).
//
// Пакет не зависит от app и adapters. Для проверки значений, у которых есть
// доменный value object (например канала действия), он опирается на domain
// своего контекста, чтобы контракт не принимал значение, недопустимое доменом.
package contracts

import (
	"net/url"

	"lead-gen/contracts/outreach-orchestration/approvedaction"
)

// Envelope — общий конверт контрактов контекста. Реэкспорт опубликованного
// контракта: форма конверта, версионирование схемы (semver) и его валидация
// определены в lead-gen/contracts/outreach-orchestration/approvedaction/envelope.go.
// Потребитель обязан отвергать MAJOR выше поддерживаемой и продолжать читать
// более высокую MINOR/PATCH (docs/domain-model.md, «Межконтекстные отношения»).
type Envelope = approvedaction.Envelope

// encodeKeyPart кодирует компонент ключа идемпотентности потребляемых контрактов.
// Без кодирования разделитель "|" внутри значения склеил бы разные пары
// компонентов в один ключ; percent-кодирование делает разбор ключа однозначным.
// Кодирование совпадает с опубликованным контрактом approved-action, поэтому ключ,
// вычисленный в разных местах, совпадает.
func encodeKeyPart(part string) string {
	return url.QueryEscape(part)
}

// IsValidSemver сообщает, является ли значение корректной semver-версией. Реэкспорт
// проверки опубликованного контракта, чтобы версия схемы понималась одинаково по
// обе стороны границы.
func IsValidSemver(version string) bool {
	return approvedaction.IsValidSemver(version)
}
