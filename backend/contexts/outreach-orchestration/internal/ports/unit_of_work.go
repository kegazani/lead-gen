package ports

import "context"

// Transaction — доступ к портам в рамках одной активной транзакции.
//
// Репозиторий и outbox, полученные из Transaction, привязаны к этой транзакции,
// поэтому запись агрегата и запись его событий выполняются атомарно: use case
// сохраняет кампанию и добавляет события, не зная, какая транзакция их
// объединяет. Transaction — узкий фасад над транзакцией, а не тип драйвера БД.
type Transaction interface {
	// Campaigns возвращает репозиторий кампаний в этой транзакции.
	Campaigns() CampaignRepository

	// Outbox возвращает outbox этой транзакции.
	Outbox() Outbox
}

// UnitOfWork — порт транзакции: выполнение функции в одной транзакции.
//
// Use case открывает транзакцию, в её контексте сохраняет агрегат и пишет
// события, затем коммитит. Если fn вернула ошибку, транзакция откатывается и
// ни агрегат, ни события не сохраняются. Так CampaignRepository и Outbox
// остаются двумя независимыми портами, а их запись связывает транзакция, а не
// общий порт.
type UnitOfWork interface {
	WithinTransaction(ctx context.Context, fn func(tx Transaction) error) error
}
