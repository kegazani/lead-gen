package domain

// Скоуп кампании для черновика, поданного через межконтекстный контракт
// утверждения.
//
// Читающий контракт решения (draftdecision) адресует черновик только непрозрачной
// ссылкой и точной версией: ни кампании, ни запуска в запросе нет. Чтобы подача и
// чтение решения разрешали один и тот же агрегат без отдельного индекса, кампания
// выводится из пары (тенант, ссылка черновика) детерминированно. Тенант входит в
// вывод, поэтому одинаковые ссылки в разных тенантах не сталкиваются.
//
// Функция чистая: одинаковый вход даёт одинаковый идентификатор, второго неявного
// состояния у неё нет.
func DraftCampaignID(tenant TenantID, draft DraftID) CampaignID {
	return CampaignID("approval:" + string(tenant) + ":" + string(draft))
}
