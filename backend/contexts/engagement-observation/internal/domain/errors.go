package domain

import "errors"

// Доменные ошибки контекста engagement-observation.
//
// Ошибка описывает нарушение правила домена, а не сбой транспорта или хранилища.
// Вызывающий различает причину через errors.Is, поэтому ошибки объявлены
// именованными значениями, а не текстом.
var (
	// ErrEmptyID — идентификатор отсутствует или состоит из пробелов.
	ErrEmptyID = errors.New("домен: пустой идентификатор")

	// ErrMissingTime — квалифицируемый сигнал без времени.
	ErrMissingTime = errors.New("домен: сигнал без времени")

	// ErrMissingEventID — доменное событие без идентификатора: его нельзя
	// дедуплицировать у потребителя.
	ErrMissingEventID = errors.New("домен: доменное событие без идентификатора")

	// ErrUnknownKind — вид взаимодействия не объявлен доменом.
	ErrUnknownKind = errors.New("домен: неизвестный вид взаимодействия")

	// ErrPixelBasedKind — сигнал опознан как трекинговый пиксель (открытие,
	// просмотр, впечатление). Policy pixel-free-observation такой сигнал не
	// квалифицирует.
	ErrPixelBasedKind = errors.New("домен: пиксельный сигнал не квалифицируется")

	// ErrUnknownConfidence — уверенность в квалификации не объявлена доменом.
	ErrUnknownConfidence = errors.New("домен: неизвестная уверенность сигнала")

	// ErrUnknownOutcome — исход не соответствует виду взаимодействия.
	ErrUnknownOutcome = errors.New("домен: исход не соответствует виду взаимодействия")

	// ErrMissingLinkRef — событие перехода без непрозрачной трекинг-ссылки.
	ErrMissingLinkRef = errors.New("домен: событие перехода без трекинг-ссылки")

	// ErrMissingTarget — событие перехода без адреса назначения.
	ErrMissingTarget = errors.New("домен: событие перехода без адреса назначения")

	// ErrInvalidSnapshot — сохранённое состояние события взаимодействия
	// внутренне противоречиво и не восстанавливается без нарушения инвариантов.
	ErrInvalidSnapshot = errors.New("домен: некорректное сохранённое состояние события взаимодействия")
)
