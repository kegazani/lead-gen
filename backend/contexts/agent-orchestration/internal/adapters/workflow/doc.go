// Package workflowadapter — durable-исполнение запуска агента на Temporal.
//
// Workflow «запуск агента» живёт в owning context agent-orchestration и двигает одну
// компанию по версии пайплайна, вызывая activities. Activities — тонкие адаптеры к
// application services контекста: доменной логики в них нет, допустимость перехода и
// идемпотентность шага решает aggregate root agent-run, инварианты — прикладной слой.
//
// Раскладка пакета — adapters, а не app: workflow-код импортирует SDK Temporal
// (внешний модуль), а внешние модули в контексте допустимы только в adapters
// (tools/importlint). Владение графом исполнения остаётся за контекстом.
//
// Долговечность: состояние запуска хранится в реляционном хранилище контекста, а не
// только в истории Temporal, поэтому после перезапуска процесса workflow продолжает
// обработку с шага, зафиксированного в агрегате, — прогресс не теряется.
//
// Payload-гигиена: аргументы workflow и activities несут только идентификаторы и
// краткое описание задания (см. platform/workflow.Rule).
