-- Лента запусков (read-поверхность консоли операций) читается по (тенант, время
-- последнего изменения) в порядке убывания с добором по идентификатору: индекс
-- обслуживает выборку списка запусков. Оператор идемпотентен (IF NOT EXISTS):
-- повторное применение не меняет схему.
--
-- Колонка updated_at теперь несёт время последнего изменения агрегата из снимка
-- (доменное время), а не время записи строки: адаптер записи передаёт
-- snapshot.updated_at. Это делает порядок ленты согласованным с доменом.

CREATE INDEX IF NOT EXISTS agent_run_feed_idx
    ON "agent-orchestration".agent_run (tenant_id, updated_at DESC, id DESC);
