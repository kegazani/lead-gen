// Реальная сеть (MTProto под пользовательским аккаунтом) в объёме среза не
// реализована и не подключается: это provider-agnostic зависимость уровня
// реализации (design.md, Открытые вопросы 1). Вместо неё даны два честных
// адаптера: Unavailable отвечает требованием авторизации, а Deterministic
// возвращает заранее заданный набор сообщений и служит развилкой проекта без
// сети. Ни один из них не выдаёт себя за рабочее подключение к Telegram.
