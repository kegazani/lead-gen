package ports

import "time"

// Clock — источник текущего времени.
//
// Сценарии читают время только через порт, чтобы тест управлял моментами
// создания и исхода доставки, не меняя доменный код и не завися от системных
// часов.
type Clock interface {
	// Now возвращает текущий момент времени.
	Now() time.Time
}
