package ports

import (
	"context"
	"errors"
)

// Резолверы непрозрачных ссылок утверждённого действия.
//
// Утверждённое действие (контракт approved-action) намеренно не несёт адреса
// получателя и содержимого письма: PII и материал разрешает владелец
// соответствующей модели в момент доставки. Контекст message-delivery держит
// только форму портов; реализации принадлежат владельцам контрактов
// (delivery-target у lead-management, версия материала — у владельца версии) и
// подключаются адаптерами. Чужие внутренние пакеты контекст не импортирует.
//
// Ошибки порта различимы: владелец сообщает либо доменный отказ (ссылка не
// разрешается), либо недоступность (сбой транспорта/владельца). Мост обязан не
// выдумывать адрес или материал при недоступности (AGENTS.md §3).
var (
	// ErrReferenceUnresolved — ссылка не разрешается у владельца: получатель или
	// версия материала неизвестны либо недоступны в границах тенанта. Доменный
	// отказ, а не сбой транспорта.
	ErrReferenceUnresolved = errors.New("порты: ссылка не разрешается")

	// ErrResolverUnavailable — резолвер недоступен: контракт не подключён или
	// сбой транспорта. Недоступность не выдаётся за успех и не подменяется
	// выдуманным значением.
	ErrResolverUnavailable = errors.New("порты: резолвер ссылок недоступен")
)

// RecipientResolver — порт разрешения непрозрачной ссылки получателя в
// проверенный адрес назначения.
//
// Реализация — адаптер контракта delivery-target (владелец lead-management):
// разрешение выполняется по тенанту, чужая ссылка не разрешается. Возвращённый
// адрес разбирается в domain.DeliveryAddress уже вызывающим, поэтому порт
// возвращает строку и явные ошибки ErrReferenceUnresolved / ErrResolverUnavailable.
type RecipientResolver interface {
	// ResolveRecipient разрешает ссылку получателя в адрес назначения. Пустой
	// адрес без ошибки означает неразрешимую ссылку и отвергается вызывающим.
	ResolveRecipient(ctx context.Context, tenantID, recipientRef string) (address string, err error)
}

// Material — разрешённое содержимое письма: тема и тело версии материала.
type Material struct {
	// Subject — тема письма.
	Subject string

	// Body — тело письма.
	Body string
}

// MaterialResolver — порт разрешения ссылки на версию материала в содержимое
// письма (тема, тело).
//
// Реализация — адаптер контракта владельца версии материала. Порт отделён от
// разрешения получателя: каждый владелец резолвит то, чем владеет, а мост лишь
// соединяет. Отсутствие ссылки (MaterialVersionRef пуст) — не ошибка: содержимое
// остаётся пустым, а не выдумывается.
type MaterialResolver interface {
	// ResolveMaterial разрешает ссылку на версию материала в тему и тело письма.
	ResolveMaterial(ctx context.Context, tenantID, materialVersionRef string) (Material, error)
}
