package ports

import (
	"context"

	"lead-gen/backend/contexts/message-delivery/internal/domain"
)

// RetryableMessages — выборка сообщений, готовых к повторной попытке доставки.
//
// Порт обслуживает роль schedule: тикер повторных окон читает сообщения, у
// которых последняя попытка завершилась временным исходом (недоступность
// провайдера), и число попыток ещё не исчерпано. Терминальные исходы провайдера
// (доставлено, жёсткий или мягкий отказ) повторной попытке не подлежат и в
// выборку не попадают.
type RetryableMessages interface {
	// ListRetryable возвращает сообщения, требующие повтора, в устойчивом
	// порядке (по возрастанию времени создания). maxAttempts ограничивает
	// число попыток: сообщение с исчерпанным лимитом не возвращается. limit
	// больше нуля ограничивает размер порции; limit <= 0 возвращает все
	// подходящие сообщения.
	ListRetryable(ctx context.Context, maxAttempts, limit int) ([]*domain.Message, error)
}
