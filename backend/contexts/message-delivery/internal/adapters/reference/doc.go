// Package reference реализует порты разрешения непрозрачных ссылок
// (ports.RecipientResolver, ports.MaterialResolver) поверх опубликованных
// контрактов владельцев: delivery-target (lead-management, получатель) и
// content-version (content-production, материал письма).
//
// Разделение ответственности. Контекст message-delivery держит только форму
// портов (internal/ports) и не импортирует внутренние пакеты владельцев. Адаптеры
// переводят исход контракта владельца в исход порта, сохраняя различие между
// доменным отказом (ссылка не разрешается) и недоступностью (сбой владельца или
// транспорта). Адрес, тема и тело не выдумываются, отказ не маскируется под успех
// (AGENTS.md §3).
//
// Материал письма разрешается адаптером ContentMaterialResolver: ссылка
// `asset_id@version_id` читается у владельца контента, тема берётся из
// Version.Subject, тело — из Version.Body.
