// Package approvedaction — адаптер-источник команд доставки из утверждённого
// действия (контракт approved-action, владелец outreach-orchestration).
//
// Адаптер реализует ports.CommandSource: роль sender читает из него
// domain.DeliveryCommand так же, как из очереди в памяти. Приём утверждённого
// действия — метод Enqueue (и совместимый с контрактом Publish): мост разрешает
// непрозрачные ссылки получателя и материала через порты-резолверы, собирает
// доменную команду и ставит её в очередь.
//
// Мост не принимает решений о допустимости: он лишь делает существующий путь
// отправки достижимым из утверждённого действия. Идемпотентность — по ключу
// (тенант, approved_action_id): повтор не создаёт второй команды. Не-email
// канал и невалидное действие отклоняются без внешнего вызова; недоступность
// резолвера — честный отказ, а не выдуманный адрес или материал.
