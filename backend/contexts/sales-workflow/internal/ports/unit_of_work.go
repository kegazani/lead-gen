package ports

import "context"

// Transaction — доступ к портам в рамках одной активной транзакции.
//
// Транзакция покрывает локальное состояние контекста (синхронизацию с CRM) и
// outbox. Сделка принадлежит внешней CRM и в локальную транзакцию не входит: её
// запись идёт через DealRepository и не может быть атомарной с записью события —
// это ограничение честно помечено в README и в doc сборки.
type Transaction interface {
	// Syncs возвращает репозиторий синхронизаций в этой транзакции.
	Syncs() CRMSyncRepository

	// Outbox возвращает outbox этой транзакции.
	Outbox() Outbox
}

// UnitOfWork — порт транзакции локального состояния: выполнение функции в одной
// транзакции.
//
// Use case открывает транзакцию, в её контексте сохраняет синхронизацию и пишет
// события, затем коммитит. Если fn вернула ошибку, транзакция откатывается и
// локальное состояние и события не сохраняются.
type UnitOfWork interface {
	WithinTransaction(ctx context.Context, fn func(tx Transaction) error) error
}
