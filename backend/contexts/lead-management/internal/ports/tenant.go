// Область хранения тенанта: активный тенант запроса как единая точка доступа к
// тенант-скоупным данным. Тенант — операционная область (аналог сессионной
// переменной хранилища), а не параметр каждого метода порта: точки установки
// единичны (граница HTTP-консоли и входы воркеров), поэтому «забыть тенант» в
// новом сценарии нельзя — без установки область пуста и совпадает с прежним
// поведением.
package ports

import "context"

// tenantKey — приватный ключ области хранения в контексте. Приватность типа не
// даёт постороннему коду подменить область чужим значением.
type tenantKey struct{}

// WithTenant возвращает контекст с активным тенантом-областью хранения. Пустая
// строка — прежнее поведение: выборка работает в тенанте по умолчанию (”).
func WithTenant(ctx context.Context, tenantID string) context.Context {
	return context.WithValue(ctx, tenantKey{}, tenantID)
}

// TenantFrom возвращает активный тенант-область хранения. Пустая строка означает,
// что область не установлена: выборка идёт в тенанте по умолчанию.
func TenantFrom(ctx context.Context) string {
	if ctx == nil {
		return ""
	}
	tenant, _ := ctx.Value(tenantKey{}).(string)
	return tenant
}
