// Package memory реализует порты контекста lead-management поверх оперативной
// памяти: репозиторий карточек компаний, репозиторий контактов, репозиторий
// исходящих писем, репозиторий шаблонов письма и хранилище заданий поиска.
//
// Адаптеры хранят не указатели на агрегаты, а снимки состояния
// (domain.CompanySnapshot, domain.ContactSnapshot), а загрузка идёт через
// domain.RehydrateCompany и domain.RehydrateContact. Поэтому сохранённый агрегат
// изолирован от вызывающего: последующие правки не меняют уже сохранённое
// состояние, а загрузка заново проверяет инварианты. Реализации не знают о
// транзакциях и SQL; состояние защищено мьютексом, поэтому они пригодны для
// `go test -race` и параллельных читателей.
