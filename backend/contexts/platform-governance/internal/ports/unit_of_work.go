package ports

import "context"

// Transaction — доступ к портам в рамках одной активной транзакции.
//
// Репозиторий тенантов, outbox и хранилище ключей идемпотентности, полученные из
// Transaction, привязаны к этой транзакции, поэтому запись агрегата, его событий
// и ключа команды выполняется атомарно: use case вызывает их, не зная, какая
// транзакция их объединяет. Transaction — узкий фасад над транзакцией, а не тип
// драйвера БД.
type Transaction interface {
	// Tenants возвращает репозиторий тенантов в этой транзакции.
	Tenants() TenantRepository

	// Outbox возвращает outbox этой транзакции.
	Outbox() Outbox

	// Idempotency возвращает хранилище ключей команд этой транзакции.
	Idempotency() Idempotency
}

// UnitOfWork — порт транзакции: выполнение функции в одной транзакции.
//
// Use case открывает транзакцию, в её контексте сохраняет агрегат, пишет события
// и ключ идемпотентности, затем коммитит. Если fn вернула ошибку, транзакция
// откатывается, и ни агрегат, ни события, ни ключ не сохраняются. Так
// TenantRepository, Outbox и Idempotency остаются независимыми портами, а их
// запись связывает транзакция, а не общий порт.
type UnitOfWork interface {
	WithinTransaction(ctx context.Context, fn func(tx Transaction) error) error
}
