package ports

import (
	"context"

	"lead-gen/backend/contexts/analytics/internal/readmodel"
)

// ProjectionStore — порт хранилища эксплуатационной проекции дашборда.
//
// Проекция — витрина, а не источник истины: порт сохраняет снимок состояния
// компании (стадию воронки и отметки времени) и возвращает сохранённые снимки
// для тёплого старта. Текст ответов компаний через порт не проходит: маскирование
// обеспечивает носитель состояния, а не только код чтения.
//
// Порт не знает о драйвере СУБД, схеме таблиц и SQL: его сигнатуры оперируют
// только типом снимка проекции. Запись идемпотентна по ключу (тенант, компания):
// повторное сохранение заменяет прежнее состояние, а не создаёт вторую строку.
type ProjectionStore interface {
	// SaveCompany сохраняет состояние компании. Повторный вызов для той же
	// компании заменяет ранее сохранённый снимок (upsert по ключу).
	SaveCompany(ctx context.Context, record readmodel.CompanyRecord) error

	// LoadCompanies возвращает все сохранённые снимки состояния компаний. Пустое
	// хранилище даёт пустой список без ошибки.
	LoadCompanies(ctx context.Context) ([]readmodel.CompanyRecord, error)
}
