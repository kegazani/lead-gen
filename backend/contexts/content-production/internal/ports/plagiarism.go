package ports

import (
	"context"
	"errors"
)

// ErrSourcesUnavailable — сторонние источники проверки недоступны: внешний движок
// (сравнение с чужими текстами) не подключён. Проверка не выдаётся за полную.
var ErrSourcesUnavailable = errors.New("порты: сторонние источники проверки недоступны")

// PlagiarismSource — порт сравнения текста со сторонними источниками. Реализуется
// адаптером движка 3.1; здесь он объявлен, чтобы сравнение с внешними источниками
// было честно недоступно без подключённого движка, а не подменялось заглушкой.
type PlagiarismSource interface {
	// Match возвращает фрагменты внешних источников, дословно совпадающие с
	// переданным текстом, либо ErrSourcesUnavailable.
	Match(ctx context.Context, text string) ([]string, error)
}
