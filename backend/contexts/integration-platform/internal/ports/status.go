package ports

import (
	"context"

	"lead-gen/contracts/integration-platform/adapterstatus"
)

// AdapterStatusReader — порт чтения состояния адаптеров интеграционной платформы
// для HTTP-поверхности роли api. Владелец данных — сам контекст: точкой сборки
// передаётся источник, знающий, какие адаптеры объявлены и сконфигурированы.
//
// Реализация обязана отдавать только значения закрытых словарей и не переносить
// свободный текст (секреты) в отдаваемые данные. nil-реализация означает, что
// источник не подключён: роль api честно сообщает о недоступности, а не выдумывает
// пустой список.
type AdapterStatusReader interface {
	// AdapterStatuses возвращает состояние объявленных адаптеров. tenant принят
	// для совместимости с тенантным потребителем; конфигурация адаптеров в этом
	// контексте процессная, а не тенантная.
	AdapterStatuses(ctx context.Context, tenant string) ([]adapterstatus.Status, error)
}
