// Package deployment — технический примитив эксплуатационной проекции: строгий
// разбор `deploy/services.yaml` в объёме точки входа (группы, механизмы, сервисы,
// роли — `deployconfig.go`) и граф сервисов и инфраструктуры консоли топологии.
// Пакет знает только форму графа и канонические источники его данных: каталог
// `architecture/domain-catalog.yaml`, конфигурацию деплоя `deploy/services.yaml`
// и объявленный перечень инфраструктуры `deploy/infrastructure.yaml`.
//
// Пакет не содержит доменных терминов и не импортирует
// `contexts/**`: деплой — эксплуатационное представление уже
// описанной проекции «контекст → сервис», а не второй владелец модели.
//
// Осознанно не поддержано:
//   - вывод состояния узлов и интенсивности рёбер из метрик — это отдельный
//     слой (наблюдение), который накладывает `Graph.WithHealth`; в статическом
//     графе состояние всегда `unknown`, а `Edge.Weight` остаётся nil;
//   - домысливание связей: если каталог не объявляет ребро, оно отсутствует;
//     если связь ссылается на неизвестный узел, загрузка завершается ошибкой.
package deployment

// Health — состояние узла или ребра. Набор значений фиксирован; отсутствие
// данных выражается `HealthUnknown`, а не подстановкой `HealthUp`.
type Health string

const (
	// HealthUp — узел или ребро отвечает штатно.
	HealthUp Health = "up"
	// HealthDegraded — узел или ребро работает с деградацией.
	HealthDegraded Health = "degraded"
	// HealthDown — узел или ребро недоступно.
	HealthDown Health = "down"
	// HealthUnknown — состояние определить нельзя. Статический граф всегда
	// начинается с этого значения.
	HealthUnknown Health = "unknown"
)

// NodeKind различает узел-сервис и инфраструктурный узел. Инфраструктурный
// узел не владеет доменной моделью и не трактуется как bounded context.
type NodeKind string

const (
	// NodeService — узел-сервис, соответствующий сервису каталога.
	NodeService NodeKind = "service"
	// NodeInfra — инфраструктурный узел (хранилище, брокер, кэш и прочее).
	NodeInfra NodeKind = "infrastructure"
)

// Node — вершина графа. Для сервиса ID равен `service` каталога; для
// инфраструктуры — идентификатор из `deploy/infrastructure.yaml`.
type Node struct {
	ID    string
	Kind  NodeKind
	Label string
	Roles []string // роли запуска (для сервисов; у инфраструктуры пусто)
	// Groups — имена групп процессов deploy, в которых объявлен сервис, в
	// лексикографическом порядке. Сервис — один узел графа, но MAY
	// присутствовать в нескольких процессах, поэтому membership множественный:
	// роль — единица размещения, а не сервис. У инфраструктуры пусто.
	Groups []string
	Zone   string // зона данных, если известна
	Health Health
	Meta   map[string]string // адреса, порты и прочее для hover-карточки
}

// PrimaryGroup — группа deploy, в колонке которой детерминированная раскладка
// размещает узел. Для сервиса в нескольких процессах это лексикографически
// первая из его групп: выбор не зависит от порядка объявления в источнике и
// потому не ломает детерминизм раскладки. Пусто — у узла без групп
// (инфраструктура или сервис вне deploy).
func (n Node) PrimaryGroup() string {
	if len(n.Groups) == 0 {
		return ""
	}
	return n.Groups[0]
}

// Edge — ребро графа, соответствующее межконтекстной связи каталога.
type Edge struct {
	ID         string
	Upstream   string
	Downstream string
	Contract   string
	Transport  string
	Mechanism  string
	// Weight — интенсивность ребра. nil означает «нет данных», а НЕ нулевую
	// интенсивность: отсутствие измерения нельзя показывать как ноль.
	Weight *float64
	Health Health
}

// Graph — модель графа. Порядок узлов детерминирован: сначала сервисы, затем
// инфраструктура, внутри каждой части — по ID; рёбра отсортированы по ID.
type Graph struct {
	Nodes []Node
	Edges []Edge
}
