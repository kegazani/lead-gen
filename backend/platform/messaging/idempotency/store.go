// Package idempotency — примитив дедупликации повторных операций.
//
// Потребитель синхронного command распознаёт повтор по стабильному ключу
// идемпотентности, а потребитель события — по event_id (design.md, Решения 3 и
// 8). Оба случая сводятся к одной операции: «видели ли ключ раньше» и «записать
// ключ». Конкретное хранилище (память, БД) задаётся реализацией Store.
package idempotency

import "context"

// Store — журнал обработанных ключей идемпотентности.
//
// Seen сообщает, обрабатывался ли ключ ранее. Record фиксирует ключ. Типичное
// применение: Seen, затем при false — выполнение эффекта и Record; порядок
// важен, потому что только Record после эффекта не даёт потерять сообщение при
// падении между проверкой и записью.
type Store interface {
	Seen(ctx context.Context, key string) (bool, error)
	Record(ctx context.Context, key string) error
}
