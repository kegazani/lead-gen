// Package workflow — platform-primitive рантайма durable-исполнения на Temporal.
//
// Пакет не владеет доменной моделью и не знает контекстов: он даёт клиента
// Temporal, host воркера и реестр регистрации workflow/activities. Наблюдаемое
// поведение (шаги фулфилмента, человеческие паузы, ветвления) задаёт owning
// bounded context, а не этот пакет. Доменных импортов здесь нет — только
// техническая обвязка уровня transport/persistence.
//
// Раскладка «один воркер на сервис»: каждый сервис-контекст поднимает свой
// воркер и регистрирует свои activities; чужие шаги вызываются через activities
// и опубликованные контракты, а не прямым импортом чужого пакета.
//
// Payload-гигиена: в аргументы workflow и activities допускаются только
// идентификаторы и корреляционные ссылки (см. Rule и CheckIdentifiersOnly).
// Сырые PII и секреты в payload не попадают.
