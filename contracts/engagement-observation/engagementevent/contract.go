package engagementevent

import "context"

// Publisher — синхронная операция контракта engagement-event: владелец
// (engagement-observation) принимает квалифицированное событие взаимодействия к
// публикации.
//
// Контракт выражен интерфейсом, а не конкретным пакетом владельца: владелец
// реализует Publisher, а потребитель (например, analytics, audience,
// outreach-orchestration) держит только этот интерфейс и не импортирует
// внутренние пакеты владельца. Чем именно связаны стороны — прямым вызовом в
// одном рантайме (in-process) или сетевым клиентом — потребителя не касается;
// способ связи выбирается топологией (design.md, Решение 2).
//
// Реализация обязана принимать context.Context, уважать дедлайн и отмену и
// соблюдать ключ идемпотентности (EngagementEvent.IdempotencyKey) так, чтобы
// повторная доставка того же события не создавала второго эффекта. Это позволяет
// заменить in-process адаптер сетевым без изменения наблюдаемого поведения.
type Publisher interface {
	// Publish принимает квалифицированное событие. Невалидный контракт не
	// доставляется: ошибка видна вызывающему, а не прячется на приёмной стороне.
	Publish(ctx context.Context, event EngagementEvent) error
}
