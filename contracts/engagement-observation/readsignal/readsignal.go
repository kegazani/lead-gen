// Package readsignal — опубликованный (published language) контракт read-signal
// контекста engagement-observation.
//
// Контракт отдаёт потребителю разрешение трекинг-перехода и учёт состоявшегося
// перехода по непрозрачной ссылке. Имя контракта объявлено каталогом доменной
// архитектуры (architecture/domain-catalog.yaml,
// contexts[engagement-observation].contracts: engagement-event, read-signal);
// владелец — capability read-tracking этого контекста.
//
// Пикселей и метрик открытий здесь нет: контракт описывает только переход по
// ссылке (architecture.md, §11, «Трекинг»). Зависимости — исключительно
// стандартная библиотека. Контракт не импортирует ни внутренние пакеты владельца,
// ни platform, поэтому владелец может реализовать интерфейсы, а потребитель —
// зависеть от контракта, не видя реализации (design.md, Решение 2).
package readsignal

import (
	"context"
	"errors"
	"time"
)

// ContractName — имя публикуемого контракта. Совпадает с объявленным в каталоге
// доменной архитектуры.
const ContractName = "read-signal"

// SchemaVersion — текущая версия схемы контракта (semver).
const SchemaVersion = "1.0.0"

// ErrNotFound — ссылка перехода неизвестна владельцу. Единственная ошибка
// контракта, которую потребитель различает: она означает «не найдено», а не отказ
// внешней системы.
var ErrNotFound = errors.New("readsignal: трекинг-ссылка не найдена")

// LinkRef — непрозрачная ссылка трекинг-перехода. Это не адрес: адрес возвращает
// владелец, и посетитель видит именно его.
type LinkRef string

// Transition — состоявшийся переход по трекинг-ссылке. Записывается только факт
// перехода: ни признака прочтения, ни идентификатора посетителя, выходящего за
// пределы, который задал владелец.
type Transition struct {
	// Link — ссылка, по которой перешёл посетитель.
	Link LinkRef
	// Target — адрес, на который перешёл посетитель.
	Target string
	// OccurredAt — момент перехода (UTC).
	OccurredAt time.Time
}

// Resolver — операция разрешения трекинг-перехода контракта read-signal:
// по непрозрачной ссылке отдаёт адрес назначения. Возвращает ErrNotFound, если
// ссылка неизвестна.
//
// Resolve — условие ответа посетителю: без адреса переходить некуда. Реализация
// обязана принимать context.Context и уважать дедлайн и отмену, чтобы замена
// транспорта не изменила наблюдаемое поведение.
type Resolver interface {
	Resolve(ctx context.Context, ref LinkRef) (string, error)
}

// Recorder — операция учёта состоявшегося перехода контракта read-signal. Отказ
// учёта не должен лишать посетителя перехода по уже разрешённой ссылке: это
// потеря статистики, а не отказ перехода, и решение принимает потребитель.
type Recorder interface {
	Record(ctx context.Context, transition Transition) error
}
