// Package audiencesnapshot объявляет опубликованный контракт audience-snapshot
// контекста audience: снимок целевой аудитории кампании.
//
// Контракт выражен типом и DTO, а не пакетами владельца: потребитель
// (outreach-orchestration, request-fulfillment) держит только эту форму и не
// импортирует внутренние пакеты контекста-владельца. Кампания ссылается на
// зафиксированный снимок, а не на живой сегмент.
//
// Через границу проходит только ссылка: идентификатор снимка, сегмент, версия,
// размер и время фиксации. Содержимое сегмента (список лидов и персональные
// данные) снимок разрешает на стороне владельца и в контракт не кладёт.
//
// Транспорт — sync/http-json (интеграция query): при co-location вызов прямой,
// при разделении сервисов — сетевой клиент; выбирает точка сборки по топологии.
//
// Зависимости — только стандартная библиотека и общий конверт контрактов.
