// Package deliverycommand объявляет опубликованный контракт delivery-command
// контекста message-delivery: команда на доставку утверждённого почтового
// действия.
//
// Контракт задаёт входной шлюз единственной роли отправки (`sender`): владелец
// (message-delivery) реализует интерфейс Port своим прикладным сценарием, а
// вызывающий (например, outreach-orchestration при co-location) держит только
// эту форму. Синхронная связь (relationship outreach-to-delivery) выбирается
// топологией: при co-location вызов прямой, при разделении сервисов — сетевой
// клиент; потребитель не импортирует внутренние пакеты владельца.
//
// Контракт несёт только идентификаторы, непрозрачные ссылки и проверенный адрес
// назначения — минимум, необходимый роли отправки. Персональных данных, темы и
// тела письма здесь нет (payload-гигиена, data-governance).
