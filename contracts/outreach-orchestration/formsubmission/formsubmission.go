// Package formsubmission — опубликованный (published language) контракт
// form-submission контекста outreach-orchestration.
//
// Контракт принимает обращение посетителя, пришедшее через публичную форму
// обратной связи, и передаёт его дальше — в приёмник в контуре клиента.
//
// # Об имени контракта
//
// Каталог доменной архитектуры отдаёт capability outreach-channel-form контексту
// outreach-orchestration (architecture/domain-catalog.yaml,
// context.capabilities), поэтому владелец контракта — outreach-orchestration.
// Объявленный набор контрактов этого контекста (approved-action, analytics-event,
// campaign-command, outreach-outcome) приёма заявки через форму не описывает:
// approved-action — команда на исполнение утверждённого оператором действия,
// analytics-event и outreach-outcome — исходящие события, campaign-command —
// команда кампании. Поэтому контракт вводится как новый, а его имя образовано от
// самой capability (outreach-channel-form) — form-submission. Если каталог позже
// объявит иное имя, это имя подлежит согласованию с каталогом.
//
// Зависимости — исключительно стандартная библиотека. Контракт не импортирует ни
// внутренние пакеты владельца, ни platform. Доменных правил здесь нет: контракт
// переносит введённые посетителем значения и признак согласия.
package formsubmission

import (
	"context"
	"errors"
	"time"
)

// ContractName — имя публикуемого контракта. См. примечание об имени в описании
// пакета: каталог отдельного имени не объявляет.
const ContractName = "form-submission"

// SchemaVersion — текущая версия схемы контракта (semver).
const SchemaVersion = "1.0.0"

// ErrNotFound — форма с запрошенной ссылкой приёмнику неизвестна. Единственная
// ошибка контракта, которую потребитель различает: посетитель пришёл по устаревшей
// ссылке, а не приёмник отказал.
var ErrNotFound = errors.New("formsubmission: форма не найдена")

// FormRef — непрозрачная ссылка на форму, которой адресована заявка. Потребитель
// не разбирает её и не выводит из неё смысл: владелец решает, что за ней стоит.
type FormRef string

// Submission — заявка посетителя, собранная формой обратной связи.
//
// Заявка содержит персональные данные, поэтому потребитель её не журналирует и не
// кэширует, а передаёт без сохранения на стороне платформы: заявки уходят в контур
// клиента (landing-page-generator, Решение 1). Платформа — передающая сторона.
type Submission struct {
	// Form — форма, через которую пришла заявка.
	Form FormRef
	// Name — имя посетителя.
	Name string
	// Contact — способ связи: почта или телефон.
	Contact string
	// Message — необязательное сообщение.
	Message string
	// Consent — согласие на обработку персональных данных. Без него заявка не
	// передаётся: согласие — не оформление, а условие приёма.
	Consent bool
	// ReceivedAt — момент приёма заявки на стороне потребителя (UTC).
	ReceivedAt time.Time
}

// Sink принимает заявку посетителя и передаёт её дальше — в приёмник в контуре
// клиента. Реализация не сохраняет заявку на стороне платформы и возвращает
// ошибку, если передача не состоялась; возвращает ErrNotFound, если форма
// неизвестна.
//
// Способ связи — прямым вызовом при co-location или сетевым клиентом при
// разделении сервисов — выбирает точка сборки по топологии (design.md,
// Решение 2). Реализация обязана принимать context.Context и уважать дедлайн и
// отмену, чтобы замена транспорта не изменила наблюдаемое поведение.
type Sink interface {
	Submit(ctx context.Context, submission Submission) error
}
